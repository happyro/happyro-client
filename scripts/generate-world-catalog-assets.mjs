import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import sharp from 'sharp';

const projectRoot = path.resolve(import.meta.dirname, '..');
const sourceDirectory = path.resolve(
	projectRoot,
	process.env.NPC_IMAGE_SOURCE || '../happyro-admin/backend/resources/game-data/world/npcs'
);
const outputDirectory = path.resolve(projectRoot, 'applications/pwa/data/world');
const serverNpcDirectory = path.resolve(projectRoot, process.env.SERVER_NPC_SOURCE || '../happyro-server/npc');
const mapImageDirectory = path.resolve(
	projectRoot,
	process.env.MAP_IMAGE_SOURCE || '../happyro-admin/backend/resources/game-data/world/maps'
);
const npcNameSource = path.resolve(projectRoot, process.env.NPC_NAME_SOURCE || 'src/DB/NpcNameTranslations.zh-CN.json');
const npcInstanceOutput = path.resolve(projectRoot, 'src/DB/Navigation/NpcInstanceNameTable.js');
const clientResourceManifest = path.resolve(
	projectRoot,
	process.env.CLIENT_RESOURCE_MANIFEST || '../../work/grf-extract/kro-20211105/data/manifest.json'
);
const serverMapConfig = path.resolve(
	projectRoot,
	process.env.SERVER_MAP_CONFIG || '../happyro-server/conf/maps_athena.conf'
);
const supportedMapOutput = path.resolve(projectRoot, 'src/DB/Map/SupportedMapTable.js');
const tileSize = 112;
const contentSize = 104;
const columns = 16;
const rows = 16;
const entriesPerSheet = columns * rows;

async function listFiles(directory) {
	const entries = await fs.readdir(directory, { withFileTypes: true });
	const files = await Promise.all(
		entries.map(entry => {
			const entryPath = path.join(directory, entry.name);
			return entry.isDirectory() ? listFiles(entryPath) : [entryPath];
		})
	);
	return files.flat();
}

function parseNpcInstances(contents, instances, npcNames) {
	for (const sourceLine of contents.split(/\r?\n/)) {
		const line = sourceLine.trim();
		if (!line || line.startsWith('//')) continue;
		const columns = line.split(/\t+/);
		if (columns.length < 4) continue;
		const location = columns[0].match(/^([a-z0-9_]+),(-?\d+),(-?\d+),\d+$/i);
		if (
			!location ||
			/^-1(?:,|$)/.test(columns[3]) ||
			!/^(?:script(?:\([^)]*\))?|shop|cashshop|itemshop|pointshop|duplicate\([^)]*\))$/i.test(columns[1])
		) {
			continue;
		}
		const sourceName = columns[2].replace(/#.*$/, '').replace(/::.*/, '').trim();
		if (!sourceName || sourceName.startsWith('#')) continue;
		const translatedName = npcNames[sourceName];
		if (!translatedName && !/[\u3400-\u9fff]/.test(sourceName)) continue;
		const candidate = {
			name: translatedName || sourceName,
			sourceName
		};
		const key = `${location[1].toLocaleLowerCase()}:${Number(location[2])}:${Number(location[3])}`;
		const current = instances[key];
		if (!current || (translatedName && current.name === current.sourceName)) instances[key] = candidate;
	}
}

async function generateSupportedMapTable() {
	const resourceManifestContents = await fs.readFile(clientResourceManifest, 'utf8');
	const serverMapConfigContents = await fs.readFile(serverMapConfig, 'utf8');
	const resourceManifest = JSON.parse(resourceManifestContents);
	const resourceExtensions = new Map();
	for (const file of resourceManifest.files || []) {
		const match = String(file.path || '').match(/^data\/([^/]+)\.(rsw|gat|gnd)$/i);
		if (!match) continue;
		const mapName = match[1].toLocaleLowerCase();
		if (!resourceExtensions.has(mapName)) resourceExtensions.set(mapName, new Set());
		resourceExtensions.get(mapName).add(match[2].toLocaleLowerCase());
	}
	const clientMaps = new Set(
		[...resourceExtensions]
			.filter(([, extensions]) => ['rsw', 'gat', 'gnd'].every(extension => extensions.has(extension)))
			.map(([mapName]) => mapName)
	);
	const serverMaps = new Set(
		[...serverMapConfigContents.matchAll(/^\s*map:\s*([a-z0-9_@-]+)\s*$/gim)].map(match =>
			match[1].toLocaleLowerCase()
		)
	);
	const supportedMaps = [...clientMaps].filter(mapName => serverMaps.has(mapName)).sort();
	const source = `// Generated by scripts/generate-world-catalog-assets.mjs. Do not edit manually.\n// Client manifest SHA256: ${crypto.createHash('sha256').update(resourceManifestContents).digest('hex')}\n// Server map config SHA256: ${crypto.createHash('sha256').update(serverMapConfigContents).digest('hex')}\nconst SupportedMapTable = new Set(${JSON.stringify(supportedMaps, null, 2)});\n\nexport function isSupportedMapResource(mapName) {\n\tconst normalized = String(mapName || '')\n\t\t.replace(/\\.(?:rsw|gat)$/i, '')\n\t\t.toLocaleLowerCase();\n\treturn SupportedMapTable.has(normalized);\n}\n\nexport default SupportedMapTable;\n`;
	await fs.writeFile(supportedMapOutput, source);
	return { clientCount: clientMaps.size, serverCount: serverMaps.size, supportedCount: supportedMaps.length };
}

const imageFiles = (await fs.readdir(sourceDirectory))
	.filter(file => /^\d+\.png$/.test(file))
	.sort((left, right) => Number.parseInt(left, 10) - Number.parseInt(right, 10));
const sourceHash = crypto.createHash('sha256');
for (const file of imageFiles) sourceHash.update(await fs.readFile(path.join(sourceDirectory, file)));
const mapImages = (await fs.readdir(mapImageDirectory))
	.filter(file => file.endsWith('.png'))
	.map(file => file.slice(0, -4).toLocaleLowerCase())
	.sort();
const mapImagesHash = crypto.createHash('sha256').update(mapImages.join('\n')).digest('hex');
const supportedMaps = await generateSupportedMapTable();

const npcInstances = {};
const npcNames = JSON.parse(await fs.readFile(npcNameSource, 'utf8'));
const serverNpcFiles = (await listFiles(serverNpcDirectory)).filter(file => file.endsWith('.txt')).sort();
const npcDefinitionsHash = crypto.createHash('sha256');
npcDefinitionsHash.update(await fs.readFile(npcNameSource));
for (const file of serverNpcFiles) {
	const contents = await fs.readFile(file, 'utf8');
	npcDefinitionsHash.update(contents);
	parseNpcInstances(contents, npcInstances, npcNames);
}
const untranslatedInstances = Object.entries(npcInstances).filter(([, npc]) => !/[\u3400-\u9fff]/.test(npc.name));
if (untranslatedInstances.length) {
	throw new Error(
		`NPC translation source leaves ${untranslatedInstances.length} instances untranslated, including ${untranslatedInstances
			.slice(0, 5)
			.map(([key, npc]) => `${key} (${npc.sourceName})`)
			.join(', ')}`
	);
}

const sortedNpcInstances = Object.fromEntries(
	Object.entries(npcInstances).sort(([left], [right]) => left.localeCompare(right))
);
await fs.writeFile(
	npcInstanceOutput,
	`// Generated by scripts/generate-world-catalog-assets.mjs. Do not edit manually.\nconst NpcInstanceNameTable = ${JSON.stringify(sortedNpcInstances)};\n\nexport function getNpcInstanceName(mapName, x, y) {\n\treturn NpcInstanceNameTable[\`${"${String(mapName || '').toLocaleLowerCase()}:${Number(x)}:${Number(y)}"}\`] || null;\n}\n\nexport default NpcInstanceNameTable;\n`
);

await fs.rm(outputDirectory, { recursive: true, force: true });
await fs.mkdir(outputDirectory, { recursive: true });

const sprites = {};
for (let sheet = 0; sheet * entriesPerSheet < imageFiles.length; sheet += 1) {
	const files = imageFiles.slice(sheet * entriesPerSheet, (sheet + 1) * entriesPerSheet);
	const composites = await Promise.all(
		files.map(async (file, tile) => {
			const resized = await sharp(path.join(sourceDirectory, file))
				.resize(contentSize, contentSize, { fit: 'inside', withoutEnlargement: true, kernel: 'nearest' })
				.png()
				.toBuffer({ resolveWithObject: true });
			const column = tile % columns;
			const row = Math.floor(tile / columns);
			sprites[Number.parseInt(file, 10)] = { atlas: sheet, tile };
			return {
				input: resized.data,
				left: column * tileSize + Math.floor((tileSize - resized.info.width) / 2),
				top: row * tileSize + Math.floor((tileSize - resized.info.height) / 2)
			};
		})
	);

	await sharp({
		create: {
			width: columns * tileSize,
			height: rows * tileSize,
			channels: 4,
			background: { r: 0, g: 0, b: 0, alpha: 0 }
		}
	})
		.composite(composites)
		.webp({ lossless: true, effort: 6 })
		.toFile(path.join(outputDirectory, `npc-atlas-${sheet}.webp`));
}

const manifest = {
	schema: 'happyro-world-assets/v3',
	source: {
		sha256: sourceHash.digest('hex'),
		npcDefinitionsSha256: npcDefinitionsHash.digest('hex'),
		mapImagesSha256: mapImagesHash,
		imageCount: imageFiles.length
	},
	atlas: { tileSize, columns, rows },
	sprites,
	mapImages
};
await fs.writeFile(path.join(outputDirectory, 'npc-assets.json'), `${JSON.stringify(manifest)}\n`);
process.stdout.write(
	`Generated ${imageFiles.length} NPC images in ${Math.ceil(imageFiles.length / entriesPerSheet)} atlases, ${mapImages.length} map image references, ${Object.keys(npcInstances).length} localized instance names, and ${supportedMaps.supportedCount} supported maps (${supportedMaps.clientCount} client, ${supportedMaps.serverCount} server).\n`
);
